def require_failure(name, proc):
    h.require(
        proc.returncode != 0,
        (
            f"{name}: adversarial action unexpectedly succeeded\n"
            f"stdout:\n{proc.stdout[-1200:]}\n"
            f"stderr:\n{proc.stderr[-1200:]}"
        ),
    )


def raw_snapshot(swap_id):
    """
    Diagnostic snapshot.

    Concrete txids/vouts are retained here for debugging, but they are
    deliberately NOT part of the portable differential fingerprint.
    """
    alice = impl.state(
        swap_id,
        "alice",
    )

    bob = impl.state(
        swap_id,
        "bob",
    )

    fields = (
        "state",
        "blake_funding_txid",
        "blake_funding_vout",
        "btc_funding_txid",
        "btc_funding_vout",
        "btc_claim_txid",
        "btc_refund_txid",
        "blake_claim_txid",
        "blake_refund_txid",
    )

    def participant(record):
        out = {
            key: record.get(key)
            for key in fields
        }

        out["knows_original_secret"] = bool(
            record.get("secret_hex")
        )

        out["knows_revealed_secret"] = bool(
            record.get("revealed_secret_hex")
        )

        return out

    return {
        "alice": participant(alice),
        "bob": participant(bob),
    }


def portable_snapshot(raw):
    """
    Implementation-independent observable result.

    We compare economic facts and knowledge, not concrete identifiers
    generated by a particular wallet, chain history, or implementation.
    """
    identity_fields = (
        "blake_funding_txid",
        "btc_funding_txid",
        "btc_claim_txid",
        "btc_refund_txid",
        "blake_claim_txid",
        "blake_refund_txid",
    )

    def participant(record):
        return {
            "state": record["state"],
            "knows_original_secret":
                record["knows_original_secret"],
            "knows_revealed_secret":
                record["knows_revealed_secret"],
            "has_blake_funding":
                bool(record["blake_funding_txid"]),
            "has_btc_funding":
                bool(record["btc_funding_txid"]),
            "has_btc_claim":
                bool(record["btc_claim_txid"]),
            "has_btc_refund":
                bool(record["btc_refund_txid"]),
            "has_blake_claim":
                bool(record["blake_claim_txid"]),
            "has_blake_refund":
                bool(record["blake_refund_txid"]),
        }

    agreement = {}

    for field in identity_fields:
        a = raw["alice"].get(field)
        b = raw["bob"].get(field)

        if a is None or b is None:
            agreement[field] = None
        else:
            agreement[field] = (a == b)

    btc_claim = (
        raw["alice"].get("btc_claim_txid")
        or raw["bob"].get("btc_claim_txid")
    )

    btc_refund = (
        raw["alice"].get("btc_refund_txid")
        or raw["bob"].get("btc_refund_txid")
    )

    blake_claim = (
        raw["alice"].get("blake_claim_txid")
        or raw["bob"].get("blake_claim_txid")
    )

    blake_refund = (
        raw["alice"].get("blake_refund_txid")
        or raw["bob"].get("blake_refund_txid")
    )

    if btc_claim and btc_refund:
        btc_branch = "conflict"
    elif btc_claim:
        btc_branch = "claim"
    elif btc_refund:
        btc_branch = "refund"
    else:
        btc_branch = "none"

    if blake_claim and blake_refund:
        blake_branch = "conflict"
    elif blake_claim:
        blake_branch = "claim"
    elif blake_refund:
        blake_branch = "refund"
    else:
        blake_branch = "none"

    return {
        "alice": participant(raw["alice"]),
        "bob": participant(raw["bob"]),
        "economic_outcome": {
            "btc_branch": btc_branch,
            "blake_branch": blake_branch,
        },
        "identity_agreement": agreement,
    }


def digest_result(seed, path, trace, final):
    value = {
        "seed": seed,
        "path": path,
        "trace": trace,
        "final": final,
    }

    raw = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
    ).encode()

    return hashlib.sha256(raw).hexdigest()


def run_noise(rng, events):
    items = list(events)
    rng.shuffle(items)

    #
    # A seed also chooses whether each safe perturbation is replayed
    # once or twice.
    #
    for name, action in items:
        count = 1 + rng.randrange(2)

        for _ in range(count):
            action()
            yield name


def crash_recover_btc_claim(
    swap_id,
    trace,
):
    """
    Crash protocol Alice after the signed BTC claim candidate has been
    durably saved but before it is broadcast.

    This is an implementation fault event, but its assertions are
    portable economic properties:

      * the crash must not advance durable settlement state;
      * the signed candidate identity must survive restart;
      * retry must reuse that exact economic candidate;
      * only active-chain confirmation may advance BTC_CLAIMED.

    The Python reference engine exposes the failpoint through an
    environment variable. Other implementations can later map the same
    scheduler event to their own crash mechanism.
    """

    before = impl.state(
        swap_id,
        "alice",
    )

    h.require(
        before["state"] == "BTC_FUNDED",
        (
            "seeded BTC-claim crash requires Alice BTC_FUNDED; "
            f"observed {before['state']}"
        ),
    )

    proc = impl.command(
        "claim-btc",
        swap_id,
        role="alice",
        expect_ok=False,
        extra_env={
            "BLAKE_SWAP_FAILPOINT":
                "after_btc_claim_candidate_save_before_broadcast",
            "BLAKE_SWAP_AUTO_MINE": "1",
        },
    )

    h.require(
        proc.returncode == CRASH_EXIT,
        (
            "seeded BTC-claim failpoint did not crash as expected; "
            f"rc={proc.returncode}\n"
            f"stdout:\n{proc.stdout[-1200:]}\n"
            f"stderr:\n{proc.stderr[-1200:]}"
        ),
    )

    crashed = impl.state(
        swap_id,
        "alice",
    )

    h.require(
        crashed["state"] == "BTC_FUNDED",
        (
            "BTC claim crash advanced durable protocol state to "
            f"{crashed['state']}"
        ),
    )

    candidate_txid = crashed.get(
        "btc_claim_txid"
    )

    candidate_hex = crashed.get(
        "btc_claim_hex"
    )

    h.require(
        bool(candidate_txid),
        "BTC claim crash lost durable candidate txid",
    )

    h.require(
        bool(candidate_hex),
        "BTC claim crash lost durable signed transaction",
    )

    h.require(
        crashed.get("btc_claim_blockhash") is None,
        "pre-broadcast BTC claim crash recorded authoritative blockhash",
    )

    trace.append(
        "crash:btc-claim:candidate-saved-before-broadcast"
    )

    #
    # First restart: recover/rebroadcast the exact durable candidate,
    # but do NOT auto-mine. Durable protocol state must remain
    # BTC_FUNDED until active-chain confirmation exists.
    #
    proc = impl.command(
        "claim-btc",
        swap_id,
        role="alice",
        expect_ok=False,
        extra_env={
            "BLAKE_SWAP_AUTO_MINE": "0",
        },
    )

    h.require(
        proc.returncode == 0,
        (
            "BTC claim restart failed while recovering durable "
            f"candidate; rc={proc.returncode}\n"
            f"stdout:\n{proc.stdout[-1200:]}\n"
            f"stderr:\n{proc.stderr[-1200:]}"
        ),
    )

    pending = impl.state(
        swap_id,
        "alice",
    )

    h.require(
        pending["state"] == "BTC_FUNDED",
        (
            "unconfirmed BTC claim restart advanced durable state "
            f"to {pending['state']}"
        ),
    )

    h.require(
        pending.get("btc_claim_txid")
        == candidate_txid,
        "BTC claim restart changed durable candidate txid",
    )

    h.require(
        pending.get("btc_claim_hex")
        == candidate_hex,
        "BTC claim restart changed durable signed transaction",
    )

    h.require(
        pending.get("btc_claim_blockhash") is None,
        "unconfirmed BTC claim restart recorded blockhash",
    )

    h.require(
        candidate_txid
        in h.btc_cli("getrawmempool"),
        "recovered BTC claim candidate is not in mempool",
    )

    trace.append(
        "restart:recover-btc-claim:pending-same-candidate"
    )

    #
    # The laboratory, not the participant, produces the confirming
    # block. Only after that active-chain fact exists may durable state
    # advance.
    #
    impl.mine_btc(1)

    trace.append(
        "confirm:btc-claim"
    )

    impl.command(
        "claim-btc",
        swap_id,
        role="alice",
        extra_env={
            "BLAKE_SWAP_AUTO_MINE": "0",
        },
    )

    recovered = impl.state(
        swap_id,
        "alice",
    )

    h.require(
        recovered["state"] == "BTC_CLAIMED",
        (
            "confirmed BTC claim recovery did not reach BTC_CLAIMED; "
            f"observed {recovered['state']}"
        ),
    )

    h.require(
        recovered.get("btc_claim_txid")
        == candidate_txid,
        "confirmed BTC claim recovery changed canonical txid",
    )

    h.require(
        recovered.get("btc_claim_hex")
        == candidate_hex,
        "confirmed BTC claim recovery changed signed transaction",
    )

    h.require(
        bool(recovered.get("btc_claim_blockhash")),
        "confirmed BTC claim recovery has no active-chain block anchor",
    )

    trace.append(
        "recover:btc-claim:confirmed-same-candidate"
    )


def race_btc_claim(
    swap_id,
    trace,
):
    """
    Launch two concurrent BTC-claim attempts through Alice's participant
    adapter.

    The scheduler does not care how an implementation serializes the
    work internally. The portable requirements are:

      * at least one attempt succeeds;
      * Alice converges to BTC_CLAIMED;
      * exactly one durable BTC-claim identity wins;
      * that transaction spends this swap's exact BTC HTLC;
      * the canonical settlement is confirmed on the active chain;
      * no competing spend of the same HTLC remains in the mempool.

    Because both calls go through the adapter, this same race can later
    be replayed against an external implementation.
    """

    before = impl.state(
        swap_id,
        "alice",
    )

    h.require(
        before["state"] == "BTC_FUNDED",
        (
            "seeded BTC-claim race requires Alice BTC_FUNDED; "
            f"observed {before['state']}"
        ),
    )

    funding_txid = before.get(
        "btc_funding_txid"
    )
    funding_vout = before.get(
        "btc_funding_vout"
    )

    h.require(
        bool(funding_txid),
        "seeded BTC-claim race has no BTC funding txid",
    )

    h.require(
        funding_vout is not None,
        "seeded BTC-claim race has no BTC funding vout",
    )

    gate = threading.Barrier(3)
    results = [None, None]
    errors = [None, None]

    def worker(index):
        try:
            gate.wait()

            results[index] = impl.command(
                "claim-btc",
                swap_id,
                role="alice",
                expect_ok=False,
            )
        except BaseException as exc:
            errors[index] = exc

    threads = [
        threading.Thread(
            target=worker,
            args=(0,),
            daemon=True,
        ),
        threading.Thread(
            target=worker,
            args=(1,),
            daemon=True,
        ),
    ]

    for thread in threads:
        thread.start()

    #
    # Release both participant calls at the same scheduler boundary.
    #
    gate.wait()

    for thread in threads:
        thread.join(timeout=90)

    h.require(
        not any(thread.is_alive() for thread in threads),
        "seeded BTC-claim race did not terminate",
    )

    h.require(
        not any(errors),
        (
            "seeded BTC-claim race raised adapter exception: "
            f"{errors}"
        ),
    )

    h.require(
        all(result is not None for result in results),
        "seeded BTC-claim race lost a participant result",
    )

    returncodes = [
        result.returncode
        for result in results
    ]

    h.require(
        any(code == 0 for code in returncodes),
        (
            "both seeded BTC-claim racers failed; "
            f"returncodes={returncodes}"
        ),
    )

    trace.append(
        "race:btc-claim:x2"
    )

    settled = impl.state(
        swap_id,
        "alice",
    )

    h.require(
        settled["state"] == "BTC_CLAIMED",
        (
            "BTC-claim race did not converge to BTC_CLAIMED; "
            f"observed {settled['state']}"
        ),
    )

    canonical_txid = settled.get(
        "btc_claim_txid"
    )

    canonical_blockhash = settled.get(
        "btc_claim_blockhash"
    )

    h.require(
        bool(canonical_txid),
        "BTC-claim race has no canonical txid",
    )

    h.require(
        bool(canonical_blockhash),
        "BTC-claim race has no canonical blockhash",
    )

    tx = h.btc_cli(
        "getrawtransaction",
        canonical_txid,
        True,
        canonical_blockhash,
    )

    h.require(
        int(tx.get("confirmations", 0)) >= 1,
        "canonical raced BTC claim is not confirmed",
    )

    exact_inputs = [
        vin
        for vin in tx.get("vin", [])
        if (
            vin.get("txid") == funding_txid
            and int(vin.get("vout", -1))
            == int(funding_vout)
        )
    ]

    h.require(
        len(exact_inputs) == 1,
        (
            "canonical raced BTC claim does not spend "
            "the exact HTLC exactly once"
        ),
    )

    #
    # Confirm that the active block contains only this settlement for
    # the exact funding outpoint.
    #
    block = h.btc_cli(
        "getblock",
        canonical_blockhash,
        2,
    )

    active_spenders = []

    for block_tx in block.get("tx", []):
        if not isinstance(block_tx, dict):
            continue

        for vin in block_tx.get("vin", []):
            if (
                vin.get("txid") == funding_txid
                and int(vin.get("vout", -1))
                == int(funding_vout)
            ):
                active_spenders.append(
                    block_tx.get("txid")
                )
                break

    h.require(
        active_spenders == [canonical_txid],
        (
            "BTC-claim race produced unexpected active-chain "
            f"HTLC spenders: {active_spenders}"
        ),
    )

    #
    # Nor may a competing spend remain live in the mempool.
    #
    competing = []

    for txid in h.btc_cli("getrawmempool"):
        memtx = h.btc_cli(
            "getrawtransaction",
            txid,
            True,
        )

        for vin in memtx.get("vin", []):
            if (
                vin.get("txid") == funding_txid
                and int(vin.get("vout", -1))
                == int(funding_vout)
            ):
                competing.append(txid)
                break

    h.require(
        not competing,
        (
            "BTC-claim race left competing HTLC spend "
            f"in mempool: {competing}"
        ),
    )

    trace.append(
        "converge:btc-claim:one-canonical-settlement"
    )


def reorg_probe_btc_claim(
    swap_id,
    trace,
):
    """
    Disconnect the block containing Alice's confirmed Bitcoin claim
    after Bob has already learned S from that claim.

    Bob's knowledge of S is irreversible local knowledge, but it is not
    settlement authority. While the claim is off the active chain Bob
    must refuse to spend the BLAKE HTLC.

    Reconsidering the block restores chain authority; settlement may
    then continue using the same learned secret.
    """

    alice = impl.state(
        swap_id,
        "alice",
    )

    bob = impl.state(
        swap_id,
        "bob",
    )

    h.require(
        alice["state"] == "BTC_CLAIMED",
        (
            "seeded BTC-claim reorg requires Alice BTC_CLAIMED; "
            f"observed {alice['state']}"
        ),
    )

    h.require(
        bob["state"] == "BTC_CLAIMED",
        (
            "seeded BTC-claim reorg requires Bob BTC_CLAIMED; "
            f"observed {bob['state']}"
        ),
    )

    h.require(
        bool(bob.get("revealed_secret_hex")),
        "Bob must know S before seeded BTC-claim reorg",
    )

    blockhash = alice.get(
        "btc_claim_blockhash"
    )

    h.require(
        bool(blockhash),
        "Alice BTC claim has no blockhash for seeded reorg",
    )

    h.btc_cli(
        "invalidateblock",
        blockhash,
    )

    trace.append(
        "reorg:disconnect-btc-claim"
    )

    try:
        #
        # Durable state and learned S remain, but active-chain truth has
        # disappeared. Economic use of S must therefore fail closed.
        #
        stale = impl.state(
            swap_id,
            "bob",
        )

        h.require(
            stale["state"] == "BTC_CLAIMED",
            (
                "BTC claim reorg unexpectedly rewrote Bob durable "
                f"checkpoint to {stale['state']}"
            ),
        )

        h.require(
            bool(stale.get("revealed_secret_hex")),
            "Bob forgot S after BTC claim reorg",
        )

        proc = impl.command(
            "claim-blake",
            swap_id,
            role="bob",
            expect_ok=False,
        )

        text = (
            (proc.stdout or "")
            + "\n"
            + (proc.stderr or "")
        )

        h.require(
            proc.returncode != 0,
            "Bob claimed BLAKE from a reorged BTC claim",
        )

        h.require(
            (
                "Bitcoin claim is no longer on the active chain"
                in text
                or
                "Bitcoin claim is not confirmed"
                in text
            ),
            (
                "reorged BTC claim was rejected for unexpected "
                f"reason:\n{text[-1600:]}"
            ),
        )

        after_reject = impl.state(
            swap_id,
            "bob",
        )

        h.require(
            after_reject["state"] == "BTC_CLAIMED",
            "failed stale-secret spend changed Bob durable state",
        )

        h.require(
            after_reject.get("blake_claim_txid") is None,
            "failed stale-secret spend persisted BLAKE claim txid",
        )

        trace.append(
            "reject:blake-claim-from-reorged-btc-claim"
        )

    finally:
        h.btc_cli(
            "reconsiderblock",
            blockhash,
        )

    trace.append(
        "reorg:restore-btc-claim"
    )

    #
    # Prove the original BTC claim is authoritative again before
    # allowing the caller to continue to BLAKE settlement.
    #
    restored = h.btc_cli(
        "getrawtransaction",
        alice["btc_claim_txid"],
        True,
        blockhash,
    )

    h.require(
        restored.get("blockhash") == blockhash,
        "restored BTC claim returned wrong block anchor",
    )

    h.require(
        int(restored.get("confirmations", 0)) >= 1,
        "restored BTC claim is not active-chain confirmed",
    )


def run_claim_seed(seed, fault_profile="none"):
    rng = random.Random(seed)
    trace = []

    swap_id = impl.make_fresh_swap()
    trace.append("create")

    impl.handshake(swap_id)
    trace.append("handshake")

    #
    # Bob must never be able to perform Alice's BLAKE funding action.
    #
    def wrong_role_blake():
        p = impl.command(
            "fund-blake",
            swap_id,
            role="bob",
            expect_ok=False,
        )
        require_failure(
            "wrong-role fund-blake",
            p,
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "reject:wrong-role-fund-blake",
                    wrong_role_blake,
                ),
            ],
        )
    )

    impl.fund_blake_and_sync(swap_id)
    trace.append("fund-and-confirm:blake")

    def duplicate_blake_receive():
        impl.command(
            "receive-blake-funded",
            swap_id,
            role="bob",
        )

    def wrong_role_btc():
        p = impl.command(
            "fund-btc",
            swap_id,
            role="alice",
            expect_ok=False,
        )
        require_failure(
            "wrong-role fund-btc",
            p,
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:blake-funded",
                    duplicate_blake_receive,
                ),
                (
                    "reject:wrong-role-fund-btc",
                    wrong_role_btc,
                ),
            ],
        )
    )

    impl.fund_btc_and_sync(swap_id)
    trace.append("fund-and-confirm:btc")

    def duplicate_btc_receive():
        impl.command(
            "receive-btc-funded",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:btc-funded",
                    duplicate_btc_receive,
                ),
            ],
        )
    )

    impl.assert_secret_separation(swap_id)
    trace.append("assert:no-transported-secret")

    if fault_profile == "settlement-crash-v1":
        crash_recover_btc_claim(
            swap_id,
            trace,
        )
    elif fault_profile == "settlement-race-v1":
        race_btc_claim(
            swap_id,
            trace,
        )
    else:
        impl.command(
            "claim-btc",
            swap_id,
            role="alice",
        )
        trace.append("claim:btc")

    impl.command(
        "publish-btc-claimed",
        swap_id,
        role="alice",
    )
    trace.append("publish:btc-claimed")

    impl.command(
        "receive-btc-claimed",
        swap_id,
        role="bob",
    )
    trace.append("receive:btc-claimed")

    def duplicate_claim_receive():
        impl.command(
            "receive-btc-claimed",
            swap_id,
            role="bob",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:btc-claimed",
                    duplicate_claim_receive,
                ),
            ],
        )
    )

    before = impl.state(
        swap_id,
        "bob",
    )

    h.require(
        before.get("revealed_secret_hex") is None,
        "Bob learned S before explicit witness extraction",
    )

    impl.command(
        "extract-secret",
        swap_id,
        role="bob",
    )
    trace.append("extract-secret:bitcoin-witness")

    if fault_profile == "reorg-v1":
        reorg_probe_btc_claim(
            swap_id,
            trace,
        )

    impl.command(
        "claim-blake",
        swap_id,
        role="bob",
    )
    trace.append("claim:blake")

    impl.command(
        "publish-blake-claimed",
        swap_id,
        role="bob",
    )
    trace.append("publish:blake-claimed")

    impl.command(
        "receive-blake-claimed",
        swap_id,
        role="alice",
    )
    trace.append("receive:blake-claimed")

    def duplicate_blake_claim_receive():
        impl.command(
            "receive-blake-claimed",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:blake-claimed",
                    duplicate_blake_claim_receive,
                ),
            ],
        )
    )

    impl.command(
        "complete",
        "--role",
        "alice",
        swap_id,
        role="alice",
    )

    impl.command(
        "complete",
        "--role",
        "bob",
        swap_id,
        role="bob",
    )

    trace.append("complete")

    impl.assert_state(
        swap_id,
        "alice",
        "COMPLETE",
    )

    impl.assert_state(
        swap_id,
        "bob",
        "COMPLETE",
    )

    return swap_id, trace


def crash_recover_btc_refund(
    swap_id,
    trace,
):
    """
    Crash protocol Bob after the signed BTC refund candidate has been
    durably saved but before broadcast.

    Recovery requirements mirror the claim-side crash invariant:

      * crash must not advance BTC_FUNDED;
      * durable refund txid + signed transaction survive;
      * restart must reuse/rebroadcast that exact candidate;
      * unconfirmed recovery must remain BTC_FUNDED;
      * only active-chain confirmation may advance BTC_REFUNDED.
    """

    before = impl.state(
        swap_id,
        "bob",
    )

    h.require(
        before["state"] == "BTC_FUNDED",
        (
            "seeded BTC-refund crash requires Bob BTC_FUNDED; "
            f"observed {before['state']}"
        ),
    )

    proc = impl.command(
        "refund-btc",
        swap_id,
        role="bob",
        expect_ok=False,
        extra_env={
            "BLAKE_SWAP_FAILPOINT":
                "after_btc_refund_candidate_save_before_broadcast",
            "BLAKE_SWAP_AUTO_MINE": "1",
        },
    )

    h.require(
        proc.returncode == CRASH_EXIT,
        (
            "seeded BTC-refund failpoint did not crash as expected; "
            f"rc={proc.returncode}\n"
            f"stdout:\n{proc.stdout[-1200:]}\n"
            f"stderr:\n{proc.stderr[-1200:]}"
        ),
    )

    crashed = impl.state(
        swap_id,
        "bob",
    )

    h.require(
        crashed["state"] == "BTC_FUNDED",
        (
            "BTC refund crash advanced durable state to "
            f"{crashed['state']}"
        ),
    )

    candidate_txid = crashed.get(
        "btc_refund_txid"
    )

    candidate_hex = crashed.get(
        "btc_refund_hex"
    )

    h.require(
        bool(candidate_txid),
        "BTC refund crash lost durable candidate txid",
    )

    h.require(
        bool(candidate_hex),
        "BTC refund crash lost durable signed transaction",
    )

    h.require(
        crashed.get("btc_refund_blockhash") is None,
        "pre-broadcast BTC refund crash recorded blockhash",
    )

    trace.append(
        "crash:btc-refund:candidate-saved-before-broadcast"
    )

    #
    # Restart without auto-mining. This must recover/rebroadcast the
    # exact candidate while leaving durable state at BTC_FUNDED.
    #
    proc = impl.command(
        "refund-btc",
        swap_id,
        role="bob",
        expect_ok=False,
        extra_env={
            "BLAKE_SWAP_AUTO_MINE": "0",
        },
    )

    h.require(
        proc.returncode == 0,
        (
            "BTC refund restart failed while recovering candidate; "
            f"rc={proc.returncode}\n"
            f"stdout:\n{proc.stdout[-1200:]}\n"
            f"stderr:\n{proc.stderr[-1200:]}"
        ),
    )

    pending = impl.state(
        swap_id,
        "bob",
    )

    h.require(
        pending["state"] == "BTC_FUNDED",
        (
            "unconfirmed BTC refund restart advanced state to "
            f"{pending['state']}"
        ),
    )

    h.require(
        pending.get("btc_refund_txid")
        == candidate_txid,
        "BTC refund restart changed candidate txid",
    )

    h.require(
        pending.get("btc_refund_hex")
        == candidate_hex,
        "BTC refund restart changed signed transaction",
    )

    h.require(
        pending.get("btc_refund_blockhash") is None,
        "unconfirmed BTC refund restart recorded blockhash",
    )

    h.require(
        candidate_txid
        in h.btc_cli("getrawmempool"),
        "recovered BTC refund candidate is not in mempool",
    )

    trace.append(
        "restart:recover-btc-refund:pending-same-candidate"
    )

    #
    # External chain confirmation is the authority.
    #
    impl.mine_btc(1)

    trace.append(
        "confirm:btc-refund"
    )

    impl.command(
        "refund-btc",
        swap_id,
        role="bob",
        extra_env={
            "BLAKE_SWAP_AUTO_MINE": "0",
        },
    )

    recovered = impl.state(
        swap_id,
        "bob",
    )

    h.require(
        recovered["state"] == "BTC_REFUNDED",
        (
            "confirmed BTC refund recovery did not reach BTC_REFUNDED; "
            f"observed {recovered['state']}"
        ),
    )

    h.require(
        recovered.get("btc_refund_txid")
        == candidate_txid,
        "confirmed BTC refund recovery changed canonical txid",
    )

    h.require(
        recovered.get("btc_refund_hex")
        == candidate_hex,
        "confirmed BTC refund recovery changed signed transaction",
    )

    h.require(
        bool(recovered.get("btc_refund_blockhash")),
        "confirmed BTC refund recovery has no block anchor",
    )

    trace.append(
        "recover:btc-refund:confirmed-same-candidate"
    )


def run_refund_seed(seed, fault_profile="none"):
    rng = random.Random(seed)
    trace = []

    swap_id = impl.make_fresh_swap()
    trace.append("create")

    impl.handshake(swap_id)
    trace.append("handshake")

    impl.fund_blake_and_sync(swap_id)
    trace.append("fund-and-confirm:blake")

    impl.fund_btc_and_sync(swap_id)
    trace.append("fund-and-confirm:btc")

    #
    # Replay funding messages in seed-selected order before timeout.
    #
    def replay_blake():
        impl.command(
            "receive-blake-funded",
            swap_id,
            role="bob",
        )

    def replay_btc():
        impl.command(
            "receive-btc-funded",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                ("replay:blake-funded", replay_blake),
                ("replay:btc-funded", replay_btc),
            ],
        )
    )

    bob = impl.state(
        swap_id,
        "bob",
    )

    current = int(
        impl.btc_height()
    )

    remaining = int(
        bob["btc_timeout"]
    ) - current

    if remaining > 0:
        #
        # The engine treats the explicit early-refund probe as a safe
        # non-settling result rather than an economic success.
        #
        early = impl.command(
            "refund-btc",
            swap_id,
            role="bob",
        )

        h.require(
            "early Bitcoin refund rejected as non-final"
            in early.stdout,
            "premature BTC refund was not rejected",
        )

        impl.assert_state(
            swap_id,
            "bob",
            "BTC_FUNDED",
        )

        trace.append("reject:premature-btc-refund")

        impl.mine_btc(remaining)
        trace.append("advance:btc-timeout")

    if fault_profile == "refund-crash-v1":
        crash_recover_btc_refund(
            swap_id,
            trace,
        )
    else:
        impl.command(
            "refund-btc",
            swap_id,
            role="bob",
        )
        trace.append("refund:btc")

    impl.command(
        "publish-btc-refunded",
        swap_id,
        role="bob",
    )
    trace.append("publish:btc-refunded")

    impl.command(
        "receive-btc-refunded",
        swap_id,
        role="alice",
    )
    trace.append("receive:btc-refunded")

    def duplicate_refund_receive():
        impl.command(
            "receive-btc-refunded",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:btc-refunded",
                    duplicate_refund_receive,
                ),
            ],
        )
    )

    alice = impl.state(
        swap_id,
        "alice",
    )

    current = int(
        impl.blake_height()
    )

    remaining = int(
        alice["blake_timeout"]
    ) - current

    if remaining > 0:
        early = impl.command(
            "refund-blake",
            swap_id,
            role="alice",
        )

        h.require(
            "Refund is correctly timelocked."
            in early.stdout,
            "premature BLAKE refund was not timelocked",
        )

        impl.assert_state(
            swap_id,
            "alice",
            "BTC_REFUNDED",
        )

        trace.append("reject:premature-blake-refund")

        impl.mine_blake(remaining)
        trace.append("advance:blake-timeout")

    impl.command(
        "refund-blake",
        swap_id,
        role="alice",
    )
    trace.append("refund:blake")

    impl.assert_state(
        swap_id,
        "alice",
        "BLAKE_REFUNDED",
    )

    bob = impl.state(
        swap_id,
        "bob",
    )

    h.require(
        bob.get("revealed_secret_hex") is None,
        "refund path revealed S to Bob",
    )

    return swap_id, trace


def run_seed(seed, fault_profile="none"):
    #
    # Path selection is itself deterministic and portable.
    #
    path = (
        "claim"
        if random.Random(seed).randrange(2) == 0
        else "refund"
    )

    if path == "claim":
        swap_id, trace = run_claim_seed(
            seed,
            fault_profile=fault_profile,
        )
    else:
        swap_id, trace = run_refund_seed(
            seed,
            fault_profile=fault_profile,
        )

    raw_final = raw_snapshot(swap_id)
    final = portable_snapshot(raw_final)

    result = {
        "seed": seed,
        "path": path,
        "fault_profile": fault_profile,
        "swap_id": swap_id,
        "trace": trace,
        "final": final,
        "raw_final": raw_final,
        "final_digest": digest_result(
            seed,
            path,
            trace,
            final,
        ),
    }

    print()
    print("SEED RESULT")
    print("===========")
    print(json.dumps(
        result,
        indent=2,
        sort_keys=True,
    ))

    return result


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--adapter",
        choices=(
            "direct",
            "json-subprocess",
        ),
        default="direct",
        help=(
            "Python/Python transport when no external "
            "participant executable is supplied."
        ),
    )

    parser.add_argument(
        "--alice-executable",
        default=None,
        help=(
            "External blake-swap-adapter-v1 executable "
            "for protocol Alice."
        ),
    )

    parser.add_argument(
        "--bob-executable",
        default=None,
        help=(
            "External blake-swap-adapter-v1 executable "
            "for protocol Bob."
        ),
    )

    parser.add_argument(
        "--fault-profile",
        choices=FAULT_PROFILES,
        default="none",
        help=(
            "Deterministic laboratory fault schedule. "
            "Default 'none' preserves the established seeded oracle."
        ),
    )

    parser.add_argument(
        "seeds",
        nargs="*",
        type=int,
        default=list(DEFAULT_SEEDS),
    )

    args = parser.parse_args()

    global impl

    def validate_external(
        participant,
    ):
        response = participant.capabilities()

        h.require(
            response.get("ok") is True,
            (
                f"{participant.role} external adapter "
                "refused capabilities request"
            ),
        )

        h.require(
            response.get("protocol")
            == "blake-swap-adapter-v1",
            (
                f"{participant.role} external adapter "
                "protocol mismatch: "
                f"{response.get('protocol')!r}"
            ),
        )

        operations = set(
            response.get(
                "operations",
                [],
            )
        )

        for operation in (
            "capabilities",
            "command",
            "state",
        ):
            h.require(
                operation in operations,
                (
                    f"{participant.role} external adapter "
                    f"missing operation {operation}"
                ),
            )

        roles = set(
            response.get(
                "roles",
                [],
            )
        )

        h.require(
            participant.role in roles,
            (
                f"external adapter does not advertise "
                f"role {participant.role}"
            ),
        )

    if (
        args.alice_executable
        or args.bob_executable
    ):
        if args.alice_executable:
            alice = ExternalJsonParticipantAdapter(
                h,
                "alice",
                args.alice_executable,
            )

            validate_external(
                alice
            )
        else:
            alice = PythonParticipantAdapter(
                h,
                "alice",
            )

        if args.bob_executable:
            bob = ExternalJsonParticipantAdapter(
                h,
                "bob",
                args.bob_executable,
            )

            validate_external(
                bob
            )
        else:
            bob = PythonParticipantAdapter(
                h,
                "bob",
            )

        impl = SwapImplementationPair(
            h,
            alice=alice,
            bob=bob,
        )

    elif args.adapter == "direct":
        impl = make_python_reference_pair(
            h
        )

    else:
        impl = (
            make_python_json_subprocess_pair(
                h
            )
        )

    print()
    print("IMPLEMENTATION PAIR")
    print("===================")
    print(
        "Alice:",
        impl.alice.name,
    )
    print(
        "Bob:  ",
        impl.bob.name,
    )

    started = time.time()
    results = []

    try:
        impl.preflight()
        h.ok("preflight")

        for seed in args.seeds:
            h.banner(
                f"SEEDED ADVERSARIAL SEQUENCE {seed}"
            )

            result = run_seed(
                seed,
                fault_profile=args.fault_profile,
            )
            results.append(result)

            h.ok(
                f"seed {seed} converged via "
                f"{result['path']} path"
            )

    except Exception as e:
        h.fail(
            "SEEDED ADVERSARIAL RUNNER",
            str(e),
        )

    elapsed = time.time() - started

    h.banner("SUMMARY")
    print(f"passes:  {h.PASS_COUNT}")
    print(f"failures:{h.FAIL_COUNT}")
    print(f"elapsed: {elapsed:.1f}s")

    if results:
        print()
        print("REPLAY CORPUS")
        print("=============")

        for result in results:
            print(
                result["seed"],
                result["path"],
                result["final_digest"][:16],
            )

    return 1 if h.FAIL_COUNT else 0


if __name__ == "__main__":
    raise SystemExit(main())
