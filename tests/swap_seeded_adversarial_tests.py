#!/usr/bin/env python3

"""
Deterministic adversarial event-sequence runner.

This does NOT fuzz Python internals.  It generates protocol-level events
that can later be replayed against another implementation.

Every command is already a fresh engine subprocess, so command boundaries
also exercise process-restart/reload behavior.
"""

import argparse
import hashlib
import json
import random
import time

import swap_protocol_tests as h


DEFAULT_SEEDS = (
    4,
    17,
    184467,
    20261004,
)


def require_failure(name, proc):
    h.require(
        proc.returncode != 0,
        (
            f"{name}: adversarial action unexpectedly succeeded\n"
            f"stdout:\n{proc.stdout[-1200:]}\n"
            f"stderr:\n{proc.stderr[-1200:]}"
        ),
    )


def raw_snapshot(swap_id):
    """
    Diagnostic snapshot.

    Concrete txids/vouts are retained here for debugging, but they are
    deliberately NOT part of the portable differential fingerprint.
    """
    alice = h.load_state(
        swap_id,
        "alice",
    )

    bob = h.load_state(
        swap_id,
        "bob",
    )

    fields = (
        "state",
        "blake_funding_txid",
        "blake_funding_vout",
        "btc_funding_txid",
        "btc_funding_vout",
        "btc_claim_txid",
        "btc_refund_txid",
        "blake_claim_txid",
        "blake_refund_txid",
    )

    def participant(record):
        out = {
            key: record.get(key)
            for key in fields
        }

        out["knows_original_secret"] = bool(
            record.get("secret_hex")
        )

        out["knows_revealed_secret"] = bool(
            record.get("revealed_secret_hex")
        )

        return out

    return {
        "alice": participant(alice),
        "bob": participant(bob),
    }


def portable_snapshot(raw):
    """
    Implementation-independent observable result.

    We compare economic facts and knowledge, not concrete identifiers
    generated by a particular wallet, chain history, or implementation.
    """
    identity_fields = (
        "blake_funding_txid",
        "btc_funding_txid",
        "btc_claim_txid",
        "btc_refund_txid",
        "blake_claim_txid",
        "blake_refund_txid",
    )

    def participant(record):
        return {
            "state": record["state"],
            "knows_original_secret":
                record["knows_original_secret"],
            "knows_revealed_secret":
                record["knows_revealed_secret"],
            "has_blake_funding":
                bool(record["blake_funding_txid"]),
            "has_btc_funding":
                bool(record["btc_funding_txid"]),
            "has_btc_claim":
                bool(record["btc_claim_txid"]),
            "has_btc_refund":
                bool(record["btc_refund_txid"]),
            "has_blake_claim":
                bool(record["blake_claim_txid"]),
            "has_blake_refund":
                bool(record["blake_refund_txid"]),
        }

    agreement = {}

    for field in identity_fields:
        a = raw["alice"].get(field)
        b = raw["bob"].get(field)

        if a is None or b is None:
            agreement[field] = None
        else:
            agreement[field] = (a == b)

    btc_claim = (
        raw["alice"].get("btc_claim_txid")
        or raw["bob"].get("btc_claim_txid")
    )

    btc_refund = (
        raw["alice"].get("btc_refund_txid")
        or raw["bob"].get("btc_refund_txid")
    )

    blake_claim = (
        raw["alice"].get("blake_claim_txid")
        or raw["bob"].get("blake_claim_txid")
    )

    blake_refund = (
        raw["alice"].get("blake_refund_txid")
        or raw["bob"].get("blake_refund_txid")
    )

    if btc_claim and btc_refund:
        btc_branch = "conflict"
    elif btc_claim:
        btc_branch = "claim"
    elif btc_refund:
        btc_branch = "refund"
    else:
        btc_branch = "none"

    if blake_claim and blake_refund:
        blake_branch = "conflict"
    elif blake_claim:
        blake_branch = "claim"
    elif blake_refund:
        blake_branch = "refund"
    else:
        blake_branch = "none"

    return {
        "alice": participant(raw["alice"]),
        "bob": participant(raw["bob"]),
        "economic_outcome": {
            "btc_branch": btc_branch,
            "blake_branch": blake_branch,
        },
        "identity_agreement": agreement,
    }


def digest_result(seed, path, trace, final):
    value = {
        "seed": seed,
        "path": path,
        "trace": trace,
        "final": final,
    }

    raw = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
    ).encode()

    return hashlib.sha256(raw).hexdigest()


def run_noise(rng, events):
    items = list(events)
    rng.shuffle(items)

    #
    # A seed also chooses whether each safe perturbation is replayed
    # once or twice.
    #
    for name, action in items:
        count = 1 + rng.randrange(2)

        for _ in range(count):
            action()
            yield name


def run_claim_seed(seed):
    rng = random.Random(seed)
    trace = []

    swap_id = h.make_fresh_swap()
    trace.append("create")

    h.handshake(swap_id)
    trace.append("handshake")

    #
    # Bob must never be able to perform Alice's BLAKE funding action.
    #
    def wrong_role_blake():
        p = h.swap_cmd(
            "fund-blake",
            swap_id,
            role="bob",
            expect_ok=False,
        )
        require_failure(
            "wrong-role fund-blake",
            p,
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "reject:wrong-role-fund-blake",
                    wrong_role_blake,
                ),
            ],
        )
    )

    h.fund_blake_and_sync(swap_id)
    trace.append("fund-and-confirm:blake")

    def duplicate_blake_receive():
        h.swap_cmd(
            "receive-blake-funded",
            swap_id,
            role="bob",
        )

    def wrong_role_btc():
        p = h.swap_cmd(
            "fund-btc",
            swap_id,
            role="alice",
            expect_ok=False,
        )
        require_failure(
            "wrong-role fund-btc",
            p,
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:blake-funded",
                    duplicate_blake_receive,
                ),
                (
                    "reject:wrong-role-fund-btc",
                    wrong_role_btc,
                ),
            ],
        )
    )

    h.fund_btc_and_sync(swap_id)
    trace.append("fund-and-confirm:btc")

    def duplicate_btc_receive():
        h.swap_cmd(
            "receive-btc-funded",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:btc-funded",
                    duplicate_btc_receive,
                ),
            ],
        )
    )

    h.assert_secret_separation(swap_id)
    trace.append("assert:no-transported-secret")

    h.swap_cmd(
        "claim-btc",
        swap_id,
        role="alice",
    )
    trace.append("claim:btc")

    h.swap_cmd(
        "publish-btc-claimed",
        swap_id,
        role="alice",
    )
    trace.append("publish:btc-claimed")

    h.swap_cmd(
        "receive-btc-claimed",
        swap_id,
        role="bob",
    )
    trace.append("receive:btc-claimed")

    def duplicate_claim_receive():
        h.swap_cmd(
            "receive-btc-claimed",
            swap_id,
            role="bob",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:btc-claimed",
                    duplicate_claim_receive,
                ),
            ],
        )
    )

    before = h.load_state(
        swap_id,
        "bob",
    )

    h.require(
        before.get("revealed_secret_hex") is None,
        "Bob learned S before explicit witness extraction",
    )

    h.swap_cmd(
        "extract-secret",
        swap_id,
        role="bob",
    )
    trace.append("extract-secret:bitcoin-witness")

    h.swap_cmd(
        "claim-blake",
        swap_id,
        role="bob",
    )
    trace.append("claim:blake")

    h.swap_cmd(
        "publish-blake-claimed",
        swap_id,
        role="bob",
    )
    trace.append("publish:blake-claimed")

    h.swap_cmd(
        "receive-blake-claimed",
        swap_id,
        role="alice",
    )
    trace.append("receive:blake-claimed")

    def duplicate_blake_claim_receive():
        h.swap_cmd(
            "receive-blake-claimed",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:blake-claimed",
                    duplicate_blake_claim_receive,
                ),
            ],
        )
    )

    h.swap_cmd(
        "complete",
        "--role",
        "alice",
        swap_id,
        role="alice",
    )

    h.swap_cmd(
        "complete",
        "--role",
        "bob",
        swap_id,
        role="bob",
    )

    trace.append("complete")

    h.assert_state(
        swap_id,
        "alice",
        "COMPLETE",
    )

    h.assert_state(
        swap_id,
        "bob",
        "COMPLETE",
    )

    return swap_id, trace


def run_refund_seed(seed):
    rng = random.Random(seed)
    trace = []

    swap_id = h.make_fresh_swap()
    trace.append("create")

    h.handshake(swap_id)
    trace.append("handshake")

    h.fund_blake_and_sync(swap_id)
    trace.append("fund-and-confirm:blake")

    h.fund_btc_and_sync(swap_id)
    trace.append("fund-and-confirm:btc")

    #
    # Replay funding messages in seed-selected order before timeout.
    #
    def replay_blake():
        h.swap_cmd(
            "receive-blake-funded",
            swap_id,
            role="bob",
        )

    def replay_btc():
        h.swap_cmd(
            "receive-btc-funded",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                ("replay:blake-funded", replay_blake),
                ("replay:btc-funded", replay_btc),
            ],
        )
    )

    bob = h.load_state(
        swap_id,
        "bob",
    )

    current = int(
        h.btc_cli("getblockcount")
    )

    remaining = int(
        bob["btc_timeout"]
    ) - current

    if remaining > 0:
        #
        # The engine treats the explicit early-refund probe as a safe
        # non-settling result rather than an economic success.
        #
        early = h.swap_cmd(
            "refund-btc",
            swap_id,
            role="bob",
        )

        h.require(
            "early Bitcoin refund rejected as non-final"
            in early.stdout,
            "premature BTC refund was not rejected",
        )

        h.assert_state(
            swap_id,
            "bob",
            "BTC_FUNDED",
        )

        trace.append("reject:premature-btc-refund")

        h.mine_btc(remaining)
        trace.append("advance:btc-timeout")

    h.swap_cmd(
        "refund-btc",
        swap_id,
        role="bob",
    )
    trace.append("refund:btc")

    h.swap_cmd(
        "publish-btc-refunded",
        swap_id,
        role="bob",
    )
    trace.append("publish:btc-refunded")

    h.swap_cmd(
        "receive-btc-refunded",
        swap_id,
        role="alice",
    )
    trace.append("receive:btc-refunded")

    def duplicate_refund_receive():
        h.swap_cmd(
            "receive-btc-refunded",
            swap_id,
            role="alice",
        )

    trace.extend(
        run_noise(
            rng,
            [
                (
                    "replay:btc-refunded",
                    duplicate_refund_receive,
                ),
            ],
        )
    )

    alice = h.load_state(
        swap_id,
        "alice",
    )

    current = int(
        h.blake_cli("getblockcount")
    )

    remaining = int(
        alice["blake_timeout"]
    ) - current

    if remaining > 0:
        early = h.swap_cmd(
            "refund-blake",
            swap_id,
            role="alice",
        )

        h.require(
            "Refund is correctly timelocked."
            in early.stdout,
            "premature BLAKE refund was not timelocked",
        )

        h.assert_state(
            swap_id,
            "alice",
            "BTC_REFUNDED",
        )

        trace.append("reject:premature-blake-refund")

        h.mine_blake(remaining)
        trace.append("advance:blake-timeout")

    h.swap_cmd(
        "refund-blake",
        swap_id,
        role="alice",
    )
    trace.append("refund:blake")

    h.assert_state(
        swap_id,
        "alice",
        "BLAKE_REFUNDED",
    )

    bob = h.load_state(
        swap_id,
        "bob",
    )

    h.require(
        bob.get("revealed_secret_hex") is None,
        "refund path revealed S to Bob",
    )

    return swap_id, trace


def run_seed(seed):
    #
    # Path selection is itself deterministic and portable.
    #
    path = (
        "claim"
        if random.Random(seed).randrange(2) == 0
        else "refund"
    )

    if path == "claim":
        swap_id, trace = run_claim_seed(seed)
    else:
        swap_id, trace = run_refund_seed(seed)

    raw_final = raw_snapshot(swap_id)
    final = portable_snapshot(raw_final)

    result = {
        "seed": seed,
        "path": path,
        "swap_id": swap_id,
        "trace": trace,
        "final": final,
        "raw_final": raw_final,
        "final_digest": digest_result(
            seed,
            path,
            trace,
            final,
        ),
    }

    print()
    print("SEED RESULT")
    print("===========")
    print(json.dumps(
        result,
        indent=2,
        sort_keys=True,
    ))

    return result


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "seeds",
        nargs="*",
        type=int,
        default=list(DEFAULT_SEEDS),
    )

    args = parser.parse_args()

    started = time.time()
    results = []

    try:
        h.preflight()
        h.ok("preflight")

        for seed in args.seeds:
            h.banner(
                f"SEEDED ADVERSARIAL SEQUENCE {seed}"
            )

            result = run_seed(seed)
            results.append(result)

            h.ok(
                f"seed {seed} converged via "
                f"{result['path']} path"
            )

    except Exception as e:
        h.fail(
            "SEEDED ADVERSARIAL RUNNER",
            str(e),
        )

    elapsed = time.time() - started

    h.banner("SUMMARY")
    print(f"passes:  {h.PASS_COUNT}")
    print(f"failures:{h.FAIL_COUNT}")
    print(f"elapsed: {elapsed:.1f}s")

    if results:
        print()
        print("REPLAY CORPUS")
        print("=============")

        for result in results:
            print(
                result["seed"],
                result["path"],
                result["final_digest"][:16],
            )

    return 1 if h.FAIL_COUNT else 0


if __name__ == "__main__":
    raise SystemExit(main())
