from coincurve import PrivateKey  # noqa: E402

import swap_protocol_tests as h  # noqa: E402

PASS = 0
FAIL = 0

RECOVERED_WALLET = "recovered"


def ok(name):
    global PASS
    PASS += 1
    print(f"PASS  {name}")


def fail(name, detail):
    global FAIL
    FAIL += 1
    print(f"FAIL  {name}")
    for line in str(detail).splitlines():
        print(f"      {line}")


def check(name, fn):
    try:
        fn()
    except Exception as e:  # noqa: BLE001
        fail(name, f"{type(e).__name__}: {e}")
    else:
        ok(name)


# ------------------------------------------------------------- WIF helper

BASE58_ALPHABET = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"


def base58check(payload):
    """
    Base58Check, so the suite can produce a real WIF.

    An operator would take the WIF from their own backup; the test
    generates the key, so it has to encode it itself.
    """

    checksum = hashlib.sha256(
        hashlib.sha256(payload).digest()
    ).digest()[:4]

    data = payload + checksum

    value = int.from_bytes(data, "big")
    encoded = ""

    while value:
        value, remainder = divmod(value, 58)
        encoded = BASE58_ALPHABET[remainder] + encoded

    for byte in data:
        if byte != 0:
            break

        encoded = "1" + encoded

    return encoded


def wif_for(secret_bytes, *, testnet=True):
    prefix = b"\xef" if testnet else b"\x80"

    return base58check(prefix + secret_bytes + b"\x01")


# ------------------------------------------------------------------ setup

SWAP_ID = None
RECOVERY_KEY = None


def make_swap_with_a_foreign_refund_key():
    """
    A funded BLAKE HTLC whose refund key the wallet does not hold.
    """

    global SWAP_ID, RECOVERY_KEY

    btc_start = int(h.btc_cli("getblockcount"))
    blake_start = int(h.blake_cli("getblockcount"))

    p = h.swap_cmd(
        "new",
        "--blake", "0.013",
        "--sats", "2600",
        "--btc-timeout", str(btc_start + 40),
        "--blake-timeout", str(blake_start + 80),
        role="alice",
    )

    SWAP_ID = h.parse_swap_id(p.stdout)

    #
    # Pin a refund key that the wallet has never seen. `publish-offer`
    # only fills in keys that are absent, so this is honoured, and the
    # HTLC is funded to a script this wallet cannot satisfy.
    #
    RECOVERY_KEY = PrivateKey()

    #
    # A full compressed public key (33 bytes, with its 02/03 prefix): the
    # wire schema requires the compressed form, and a descriptor's `pk()`
    # is expressed in the same form.
    #
    recovery_pub = (
        RECOVERY_KEY
        .public_key
        .format(compressed=True)
        .hex()
    )

    path = h.state_file(SWAP_ID, "alice")
    record = json.loads(path.read_text())
    record["blake_alice_pub"] = recovery_pub
    path.write_text(
        json.dumps(record, indent=2, sort_keys=True) + "\n"
    )

    h.handshake(SWAP_ID)
    h.fund_blake_and_sync(SWAP_ID)

    h.assert_state(SWAP_ID, "alice", "BLAKE_FUNDED")

    return recovery_pub


def htlc_address():
    plan = h.swap_cmd("recovery-plan", SWAP_ID, role="alice").stdout

    for line in plan.splitlines():
        if line.startswith("address:"):
            return line.split(":", 1)[1].strip()

    raise AssertionError(f"the plan contained no address:\n{plan}")


def wallet_can_spend(address, wallet):
    info = h.blake_cli(
        "getaddressinfo",
        address,
        wallet=wallet,
    )

    return bool(isinstance(info, dict) and info.get("solvable"))


# ------------------------------------------------------------------ tests


def test_the_original_wallet_cannot_spend_it():
    address = htlc_address()

    if wallet_can_spend(address, h.ALICE_WALLET):
        raise AssertionError(
            "the funded HTLC is solvable by the original wallet, so this "
            "drill would not be testing recovery at all"
        )

    h.ok("the HTLC is not spendable by the original wallet")


def test_the_plan_reports_what_is_needed():
    plan = h.swap_cmd("recovery-plan", SWAP_ID, role="alice").stdout

    for expected in (
        "HTLC RECOVERY PLAN",
        "descriptor:",
        "address:",
        "your branch: refund",
        "wallet can spend: no",
        "getdescriptorinfo",
        "importdescriptors",
        'timestamp',
        "PASS: recovery plan generated",
    ):
        if expected not in plan:
            raise AssertionError(
                f"the recovery plan omitted {expected!r}:\n{plan}"
            )

    if "your key:" not in plan:
        raise AssertionError(f"the plan did not name the key:\n{plan}")

    h.ok("the plan names the descriptor, the branch and the steps")



WATCH_WALLET = "blake-swap-recovery-watch"


def test_the_watch_only_wallet_makes_it_solvable():
    """
    The automatic half: a funded HTLC is recorded in a dedicated
    watch-only wallet before any funds move.

    What the wallet must prove is that it can *solve* the output without
    being able to *sign* for it: `solvable` true with `ismine` false, in a
    wallet whose private keys are disabled. That is the difference
    between a second copy of the swap and a second copy of the keys.
    """
    address = htlc_address()

    result = h.swap_cmd(
        "watch-htlc",
        SWAP_ID,
        "--chain", "blake",
        role="alice",
        extra_env={
            "BLAKE_SWAP_BLAKE_WATCH_WALLET": WATCH_WALLET,
        },
    )

    for expected in (
        "PASS: descriptor imported into the watch-only wallet",
        "PASS: this HTLC is solvable",
    ):
        if expected not in result.stdout:
            raise AssertionError(
                f"watch-htlc did not report {expected!r}:\n{result.stdout}"
            )

    info = h.blake_cli(
        "getaddressinfo",
        address,
        wallet=WATCH_WALLET,
    )

    if not isinstance(info, dict) or not info.get("solvable"):
        raise AssertionError(
            f"the watch-only wallet cannot solve the HTLC: {info}"
        )

    #
    # `ismine` is true for a descriptor the wallet watches, which is not
    # the property that matters. `iswatchonly` and the wallet's own
    # `private_keys_enabled` are.
    #
    #
    # In a descriptor wallet Core reports `ismine: true` and
    # `iswatchonly: false` for a descriptor it merely watches, so neither
    # says what matters. The two facts that do are that the wallet has
    # private keys disabled and that the address is nevertheless solvable
    # -- and that the descriptor it holds is this HTLC's, with every key
    # public.
    #
    wallet_info = h.blake_cli("getwalletinfo", wallet=WATCH_WALLET)

    if wallet_info.get("private_keys_enabled"):
        raise AssertionError(
            "the watch-only wallet has private keys enabled, so it is "
            "not the separate copy this design depends on"
        )

    descriptors = h.blake_cli(
        "listdescriptors",
        wallet=WATCH_WALLET,
    )

    held = [
        entry["desc"]
        for entry in descriptors.get("descriptors", [])
        if address == h.blake_cli(
            "deriveaddresses",
            entry["desc"],
        )[0]
    ]

    if not held:
        raise AssertionError(
            "the watch-only wallet does not hold this HTLC's descriptor"
        )

    if any(marker in held[0] for marker in ("prv", "wif", "xprv", "tprv")):
        raise AssertionError(
            f"the imported descriptor is not the public form: {held[0]}"
        )

    h.ok("the watch-only wallet solves the HTLC without owning it")


def test_the_original_wallet_still_cannot_spend_it():
    """
    Recording a watch-only copy must not change what the signing wallet
    can do: the test's whole premise is that the original wallet has lost
    access to this output.
    """
    if wallet_can_spend(htlc_address(), h.ALICE_WALLET):
        raise AssertionError(
            "the original wallet can now solve the HTLC, so the "
            "watch-only import changed the signing path"
        )

    h.ok("the original signing wallet still cannot spend it")

def test_the_private_descriptor_imports_into_a_fresh_wallet():

    """
    The actual recovery step. Core requires the checksum of the exact
    string being imported, and substituting a key changes it, so the
    checksum has to be recomputed -- importing the public descriptor's
    checksum fails.
    """

    h.ensure_wallet(
        h.blake_cli,
        "blake",
        RECOVERED_WALLET,
    )

    public_body = None

    plan = h.swap_cmd("recovery-plan", SWAP_ID, role="alice").stdout

    for line in plan.splitlines():
        if line.startswith("descriptor:"):
            public_body = (
                line.split(":", 1)[1].strip().split("#")[0]
            )
            break

    if not public_body:
        raise AssertionError("the plan contained no descriptor")

    recovery_pub = (
        RECOVERY_KEY.public_key.format(compressed=True).hex()
    )

    if recovery_pub not in public_body:
        raise AssertionError(
            "the plan's descriptor does not contain the refund key"
        )

    private_body = public_body.replace(
        recovery_pub,
        wif_for(RECOVERY_KEY.secret),
    )

    if private_body == public_body:
        raise AssertionError("the WIF substitution changed nothing")

    info = h.blake_cli("getdescriptorinfo", private_body)

    if not isinstance(info, dict) or not info.get("checksum"):
        raise AssertionError(f"no checksum for the private form: {info}")

    if not info.get("hasprivatekeys"):
        raise AssertionError(
            "the node did not see the substituted key as private"
        )

    #
    # The checksum from `getdescriptorinfo` is the checksum of the string
    # it was given, so it belongs to *our* private form. The `descriptor`
    # field it returns is the canonical PUBLIC form (the WIF replaced by
    # its derived public key), and importing that would fail with "cannot
    # import descriptor without private keys" -- the checksum matches, but
    # the keys are gone.
    #
    descriptor = private_body + "#" + info["checksum"]

    result = h.blake_cli(
        "importdescriptors",
        json.dumps(
            [
                {
                    "desc": descriptor,
                    "timestamp": "now",
                }
            ]
        ),
        wallet=RECOVERED_WALLET,
    )

    if not isinstance(result, list) or not result[0].get("success"):
        raise AssertionError(f"the import failed: {result}")

    h.ok("the private descriptor imports with its own checksum")


def test_the_recovered_wallet_can_spend_it():
    address = htlc_address()

    if not wallet_can_spend(address, RECOVERED_WALLET):
        raise AssertionError(
            "the recovered wallet still cannot solve the HTLC"
        )

    h.ok("the recovered wallet can solve the HTLC")


def test_the_recovered_wallet_performs_the_refund():
    """
    Recovery is only real if the funds move. The refund branch also needs
    the locktime mature, and the pre-BTC refund rule needs Bitcoin to be
    independently absent.
    """

    state = h.load_state(SWAP_ID, "alice")

    height = int(h.blake_cli("getblockcount"))
    timeout = int(state["blake_timeout"])

    if timeout > height:
        h.mine_blake(timeout - height)

    h.swap_cmd(
        "refund-blake",
        SWAP_ID,
        role="alice",
        #
        # `BLAKE_SWAP_BLAKE_WALLET` outranks `BLAKE_SWAP_CHAIN_WALLET`
        # (chain-specific overrides win, for backwards compatibility), and
        # the harness sets both, so the recovery wallet must be named in
        # the specific variable or the original wallet signs instead and
        # the PSBT simply never finalizes.
        #
        extra_env={
            "BLAKE_SWAP_BLAKE_WALLET": RECOVERED_WALLET,
            "BLAKE_SWAP_CHAIN_WALLET": RECOVERED_WALLET,
            "BLAKE_SWAP_BTC_WALLET": RECOVERED_WALLET,
        },
    )

    h.assert_state(SWAP_ID, "alice", "BLAKE_REFUNDED")

    refunded = h.load_state(SWAP_ID, "alice")

    if not refunded.get("blake_refund_txid"):
        raise AssertionError("no refund transaction was recorded")

    #
    # And the chain agrees: the refund branch spent the HTLC.
    #
    address = htlc_address()

    info = h.blake_cli("getaddressinfo", address, wallet=RECOVERED_WALLET)

    if int(info.get("confirmations", 0) or 0) != 0 and info.get("ismine"):
        raise AssertionError("the HTLC address still holds the output")

    h.ok("the recovered wallet refunded the HTLC")


def main():
    print()
    print("=" * 72)
    print("HTLC KEY RECOVERY (regtest)")
    print("=" * 72)
    print()

    started = time.time()

    try:
        h.preflight()
        ok("preflight")

        try:
            make_swap_with_a_foreign_refund_key()
            ok("funded an HTLC whose refund key this wallet never held")
        except Exception as e:  # noqa: BLE001
            fail("set up a recoverable HTLC", str(e))
            raise

        check("the original wallet cannot spend the HTLC", test_the_original_wallet_cannot_spend_it)
        check("the watch-only wallet solves it without owning it", test_the_watch_only_wallet_makes_it_solvable)
        check("the signing wallet is unchanged", test_the_original_wallet_still_cannot_spend_it)
        check("the plan reports what is needed", test_the_plan_reports_what_is_needed)
        check("the private descriptor imports into a fresh wallet", test_the_private_descriptor_imports_into_a_fresh_wallet)
        check("the recovered wallet can solve the HTLC", test_the_recovered_wallet_can_spend_it)
        check("the recovered wallet performs the refund", test_the_recovered_wallet_performs_the_refund)
    except Exception as e:  # noqa: BLE001
        fail("HARNESS", str(e))

    print()
    print("=" * 72)
    print("HTLC KEY RECOVERY SUMMARY")
    print("=" * 72)
    print(f"passes:   {PASS}")
    print(f"failures: {FAIL}")
    print(f"elapsed:  {time.time() - started:.1f}s")
    print()
    print(f"swap: {SWAP_ID}")
    print()
    print("Local regtest only.")

    return 1 if FAIL else 0


if __name__ == "__main__":
    raise SystemExit(main())
