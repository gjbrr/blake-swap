#!/usr/bin/env python3
"""
HTLC key recovery suite.

Signing a claim or a refund depends on the participant's wallet holding the
private keys behind the HTLC's addresses. A wallet restore, rename or
re-creation that loses them makes **both** the claim and the refund
impossible, and nothing in the swap record says so.

The recovery procedure is: rebuild the HTLC descriptor from the swap record
with your own private key substituted for your public key, import it
(which requires the checksum of the exact string being imported, because
substituting a key changes it), and then spend. This suite performs that
drill for real:

  * a swap is funded into an HTLC whose refund key this wallet has **never
    held** (the key is generated by the test, so there is no wallet
    shortcut to hide behind);
  * the original wallet cannot spend it;
  * `recovery-plan` reports the descriptor, its checksum, which branch
    belongs to this participant, and that the wallet cannot spend it;
  * importing the private-key descriptor into a **fresh wallet** makes the
    output solvable again;
  * that fresh wallet then performs the actual refund, and the HTLC is
    spent by the refund branch.

Core's constraints are exercised as part of the drill rather than assumed:
`getdescriptorinfo` on the substituted string, and `importdescriptors` with
`"timestamp": "now"` (a `.pth`-free checkout... a numeric timestamp or a
zero timestamp would trigger a rescan).

Needs the two-chain regtest rig, and the BLAKE node for the wallet it
creates.

Exit status: 0 pass, 1 fail.
"""

from __future__ import annotations

