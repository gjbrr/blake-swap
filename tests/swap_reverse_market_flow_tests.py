#!/usr/bin/env python3
"""
End-to-end REVERSE market swap: `btc-for-blake`, on regtest, over a local
relay stub.

In this direction the market roles invert: the **maker is protocol Bob**
(selling BTC) and the **taker is protocol Alice** (selling BLAKE). The
secret must therefore be generated by the *taker*, not the maker, and the
maker must reserve a public swap id without ever creating or learning S.

That inversion is what this suite exists to prove, and it is the path
most of the acceptance machinery in `command_accept_reverse_market_match`
and `command_accept_reverse_swap_offer` lives on:

    maker(Bob)   publish-market-offer --direction btc-for-blake
    taker(Alice) take-market-offer
    maker(Bob)   accept-market-take        -> reserves swap_id, publishes
                                              the match, creates NO secret
    taker(Alice) accept-reverse-market-match -> creates S and the binding
    taker(Alice) publish-offer             -> publishes the protocol offer
    maker(Bob)   accept-reverse-swap-offer -> imports it, publishes accept
    ...          then the ordinary settlement sequence to COMPLETE
"""

from __future__ import annotations

import contextlib
import io
import json
import sys
import tempfile
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(HERE))

from nostr_relay_stub import NostrRelayStub  # noqa: E402

import swap_protocol_tests as h  # noqa: E402

PASS = 0
FAIL = 0


def ok(name):
    global PASS
    PASS += 1
    print(f"PASS  {name}")


def fail(name, detail):
    global FAIL
    FAIL += 1
    print(f"FAIL  {name}")
    for line in str(detail).splitlines():
        print(f"      {line}")


def check(name, fn):
    try:
        fn()
    except Exception as e:  # noqa: BLE001
        fail(name, f"{type(e).__name__}: {e}")
    else:
        ok(name)


# ---------------------------------------------------------------- setup

STUB = NostrRelayStub()
RELAY_URL = STUB.start()

BASE = Path(tempfile.mkdtemp(prefix="blake-reverse-flow-"))

PROFILES = {
    "alice": {
        "state": BASE / "alice",
        "key": BASE / "alice" / "participant.key",
        "wallet": h.ALICE_WALLET,
        "secret": "11" * 32,
    },
    "bob": {
        "state": BASE / "bob",
        "key": BASE / "bob" / "participant.key",
        "wallet": h.BOB_WALLET,
        "secret": "22" * 32,
    },
}

for profile in PROFILES.values():
    profile["state"].mkdir(parents=True, exist_ok=True)
    profile["key"].write_text(profile["secret"] + "\n")
    profile["key"].chmod(0o600)


def run(role, *args, expect_ok=True):
    profile = PROFILES[role]

    return h.run(
        [sys.executable, h.SWAP_V2, *args],
        expect_ok=expect_ok,
        env={
            "BLAKE_SWAP_TRANSPORT": "nostr",
            "BLAKE_SWAP_NOSTR_RELAYS": RELAY_URL,
            "BLAKE_SWAP_ROLE": role,
            "BLAKE_SWAP_STATE_DIR": str(profile["state"]),
            "BLAKE_SWAP_MESSAGE_DIR": str(profile["state"] / "messages"),
            "BLAKE_SWAP_CHAIN_WALLET": profile["wallet"],
            "BLAKE_SWAP_PARTICIPANT_KEY_FILE": str(profile["key"]),
        },
    )


def quiet(fn, *args, **kwargs):
    with contextlib.redirect_stdout(io.StringIO()):
        return fn(*args, **kwargs)


def stub_events(tag):
    return [
        event
        for event in STUB.events.values()
        if any(
            len(t) >= 2 and t[0] == "t" and t[1] == tag
            for t in event.get("tags", [])
        )
    ]


def newest(tag):
    events = stub_events(tag)

    if not events:
        raise AssertionError(f"no {tag} event was published")

    return sorted(
        events,
        key=lambda e: (int(e.get("created_at", 0)), e.get("id", "")),
    )[-1]


def state_path(role, swap_id):
    return PROFILES[role]["state"] / f"{swap_id}.json"


def load_state(role, swap_id):
    path = state_path(role, swap_id)

    if not path.exists():
        raise AssertionError(f"no {role} state for {swap_id}")

    return json.loads(path.read_text())


# ------------------------------------------------------------ the flow

SWAP_ID = None
MATCH_ID = None


def test_reverse_market_swap_completes():
    global SWAP_ID, MATCH_ID

    # 1. Maker is Bob for btc-for-blake.
    quiet(
        run,
        "bob",
        "publish-market-offer",
        "--blake", "0.2",
        "--sats", "30000",
        "--minutes", "30",
        "--direction", "btc-for-blake",
    )

    offer_event = newest("blake-swap-market")
    offer_message = json.loads(offer_event["content"])

    assert offer_message["direction"] == "btc-for-blake", offer_message

    # 2. Taker is Alice.
    quiet(run, "alice", "take-market-offer", offer_event["id"])

    take_event = newest("blake-swap-market-take")
    take_message = json.loads(take_event["content"])

    assert take_message["maker_role"] == "bob", take_message
    assert take_message["taker_role"] == "alice", take_message

    # 3. The maker reserves the swap id and publishes the match. It must
    #    NOT create a secret: that is the taker's job in this direction.
    quiet(run, "bob", "accept-market-take", take_event["id"])

    match_event = newest("blake-swap-market-match")
    MATCH_ID = match_event["id"]
    SWAP_ID = json.loads(match_event["content"])["swap_id"]

    # 4. Taker imports the match: this is where S is created.
    quiet(run, "alice", "accept-reverse-market-match", MATCH_ID)

    alice = load_state("alice", SWAP_ID)

    assert alice.get("secret_hex"), "taker did not create the secret"

    binding = (
        PROFILES["alice"]["state"]
        / "market-match-bindings"
        / f"{SWAP_ID}.json"
    )
    assert binding.exists(), "reverse-market binding was not written"

    # 5. Taker publishes the protocol offer; maker imports it.
    #
    #    The maker must NOT surface this step before the offer exists:
    #    there is nothing to accept yet, and `next` refusing to guess is
    #    the property that keeps the reverse path from deadlocking on a
    #    missing message.
    before = run("bob", "next")
    before_text = before.stdout + before.stderr

    assert "NOTHING TO DO" in before_text, before_text

    quiet(run, "alice", "publish-offer", SWAP_ID)

    assert stub_events("blake-swap"), "protocol offer was not published"

    #
    #    With the offer present, `next` must find exactly one safe step
    #    -- importing the offer as protocol Alice's counterparty -- and
    #    perform it. That is the reverse maker's whole autonomous path.
    #
    next_result = run("bob", "next")
    next_text = next_result.stdout + next_result.stderr

    assert "NEXT SAFE STEP" in next_text, next_text
    assert "Accept reverse swap offer" in next_text, next_text

    bob = load_state("bob", SWAP_ID)
    assert bob["state"] == "OFFERED", bob["state"]

    #
    #    Re-running the same import must be idempotent. This is the
    #    crash-retry path: Bob may have imported the offer and died
    #    before recording it, so a second run has to recognise its own
    #    earlier work instead of importing the offer twice.
    #
    repeat = run("bob", "accept-reverse-swap-offer", MATCH_ID)
    repeat_text = repeat.stdout + repeat.stderr

    assert (
        "REVERSE SWAP OFFER ALREADY IMPORTED" in repeat_text
        or "REVERSE BOB HANDSHAKE RECOVERED" in repeat_text
    ), repeat_text

    bob = load_state("bob", SWAP_ID)
    assert bob["state"] == "OFFERED", bob["state"]

    # 6. Settlement.
    quiet(run, "alice", "receive-accept", SWAP_ID)

    sequence = [
        ("alice", "fund-blake"),
        ("alice", "publish-blake-funded"),
        ("bob", "receive-blake-funded"),
        ("bob", "fund-btc"),
        ("bob", "publish-btc-funded"),
        ("alice", "receive-btc-funded"),
        ("alice", "claim-btc"),
        ("alice", "publish-btc-claimed"),
        ("bob", "receive-btc-claimed"),
        ("bob", "extract-secret"),
        ("bob", "claim-blake"),
        ("bob", "publish-blake-claimed"),
        ("alice", "receive-blake-claimed"),
    ]

    for role, command in sequence:
        quiet(run, role, command, SWAP_ID)

    assert load_state("alice", SWAP_ID)["state"] == "BLAKE_CLAIMED"
    assert load_state("bob", SWAP_ID)["state"] == "BLAKE_CLAIMED"


def test_maker_never_held_the_secret():
    """
    The whole point of the reverse direction: the maker reserved the
    swap and signed the match, but S is Alice's and reaches Bob only
    through the confirmed Bitcoin claim.
    """
    bob = load_state("bob", SWAP_ID)
    alice = load_state("alice", SWAP_ID)

    # Bob recovered S from the chain...
    assert bob.get("revealed_secret_hex"), "Bob never recovered the secret"
    assert bob["revealed_secret_hex"] == alice["secret_hex"], (
        "recovered secret differs from the taker's"
    )

    # ...and never held it as his own.
    assert not bob.get("secret_hex"), "Bob holds a secret of his own"


def test_no_event_carried_the_secret():
    for event in STUB.events.values():
        assert "secret_hex" not in event.get("content", ""), (
            "a coordination event mentioned secret_hex"
        )


def test_both_complete():
    quiet(run, "alice", "complete", SWAP_ID, "--role", "alice")
    quiet(run, "bob", "complete", SWAP_ID, "--role", "bob")

    assert load_state("alice", SWAP_ID)["state"] == "COMPLETE"
    assert load_state("bob", SWAP_ID)["state"] == "COMPLETE"


def test_reconcile_reports_reverse_roles():
    result = run("bob", "reconcile", SWAP_ID, "--json")

    text = result.stdout.strip()
    payload = json.loads(text[text.index("{"):])

    # Bob is the maker and therefore protocol Bob in this direction.
    assert payload["protocol_role"] == "bob", payload
    assert payload["checkpoint_state"] == "COMPLETE", payload


def test_accept_match_performs_the_whole_reverse_step():
    """
    `accept-match` is the explicit form of the step `next` performs for a
    reverse-direction taker. It must do all of it: import the match
    (creating S), publish Alice's ordinary protocol offer, and be
    idempotent when it is run again.

    This drives a second negotiation so it cannot disturb the settled one.
    """

    before_offers = {event["id"] for event in stub_events("blake-swap-market")}

    quiet(
        run,
        "bob",
        "publish-market-offer",
        "--blake", "0.35",
        "--sats", "45000",
        "--minutes", "30",
        "--direction", "btc-for-blake",
    )

    new_offers = sorted(
        {event["id"] for event in stub_events("blake-swap-market")} - before_offers
    )

    assert len(new_offers) == 1, new_offers

    quiet(run, "alice", "take-market-offer", new_offers[0])

    take_id = newest("blake-swap-market-take")["id"]

    quiet(run, "bob", "accept-market-take", take_id)

    match_event = newest("blake-swap-market-match")
    match_id = match_event["id"]
    swap_id = json.loads(match_event["content"])["swap_id"]

    before_protocol_offers = len(stub_events("blake-swap"))

    # 1. The explicit step: import + publish Alice's offer.
    result = run("alice", "accept-match", match_id)
    text = result.stdout + result.stderr

    assert "Importing reverse-direction match as protocol Alice." in text, text

    alice = load_state("alice", swap_id)

    assert alice.get("secret_hex"), "accept-match did not create the secret"

    assert len(stub_events("blake-swap")) == before_protocol_offers + 1, (
        "accept-match did not publish Alice's protocol offer"
    )

    # 2. Running it again must not import a second time. After the import
    #    the match is no longer pending, so the answer comes from the
    #    durable binding the import wrote and the command reports the
    #    duplicate instead of failing: a crash retry of a command that
    #    already succeeded is not an error. (This used to refuse with
    #    "No pending valid match begins with ..." — NEW-15 in the
    #    correctness review, fixed by reading the durable binding first.)
    repeat = run("alice", "accept-match", match_id)

    repeat_text = repeat.stdout + repeat.stderr

    assert "MARKET MATCH ALREADY IMPORTED" in repeat_text, repeat_text

    alice = load_state("alice", swap_id)

    assert alice["state"] == "OFFERED", (
        "a repeat accept-match changed Alice's checkpoint"
    )
    assert alice.get("secret_hex"), "a repeat accept-match lost the secret"

    assert len(stub_events("blake-swap")) == before_protocol_offers + 1, (
        "a repeat accept-match published a second protocol offer"
    )

    #
    # And a prefix that matches nothing locally still refuses: the
    # friendly branch must not have swallowed the fail-closed guard.
    #
    unknown = run(
        "alice",
        "accept-match",
        "f" * 64,
        expect_ok=False,
    )

    assert unknown.returncode != 0, unknown.stdout
    assert (
        "No pending valid match begins with" in unknown.stdout + unknown.stderr
    ), unknown.stdout


def test_market_match_labels_follow_the_direction():
    """
    In `btc-for-blake` the market roles still read maker/taker but the
    protocol roles they bind invert: the maker is protocol Bob and the
    taker is protocol Alice. The human view must say so, rather than
    repeating the blake-for-btc labels.
    """

    view = run("alice", "market-matches").stdout

    assert "MARKET MATCHES FOR TAKER" in view, view
    assert "direction: btc-for-blake" in view, view
    assert "maker is protocol: bob" in view, view
    assert "taker is protocol: alice" in view, view
    assert "FOR BOB" not in view, view


def main():
    print()
    print("=" * 72)
    print("REVERSE MARKET SWAP btc-for-blake (regtest + local relay stub)")
    print("=" * 72)
    print()
    print("relay:", RELAY_URL)
    print("state:", BASE)
    print()

    try:
        h.preflight()
        ok("preflight")

        check("the reverse (btc-for-blake) market path completes a swap", test_reverse_market_swap_completes)
        check("the maker never held the secret", test_maker_never_held_the_secret)
        check("no coordination event ever carried secret_hex", test_no_event_carried_the_secret)
        check("both participants reach COMPLETE", test_both_complete)
        check("reconcile derives the maker's reverse protocol role", test_reconcile_reports_reverse_roles)
        check("accept-match performs the whole reverse step", test_accept_match_performs_the_whole_reverse_step)
        check("market-match labels follow the direction", test_market_match_labels_follow_the_direction)
    finally:
        STUB.stop()

    print()
    print("=" * 72)
    print("REVERSE MARKET FLOW SUMMARY")
    print("=" * 72)
    print(f"passes:   {PASS}")
    print(f"failures: {FAIL}")
    print()
    print(f"swap: {SWAP_ID}")
    print(
        f"stub traffic: connections={STUB.connections} "
        f"published={STUB.published} requests={STUB.requests}"
    )
    print()

    return 1 if FAIL else 0


if __name__ == "__main__":
    raise SystemExit(main())
